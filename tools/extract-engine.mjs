// Pull the landscape engine out of upstream/index.html, verbatim, into src/engine/upstream-engine.js.
//   node tools/extract-engine.mjs
// upstream/index.html is an untouched copy of LingDong-/shan-shui-inf@9f754d2 (MIT).
// Takes the first six <script> blocks (PRNG, seed parsing, Perlin noise, PolyTools, Util, the
// generators + chunk loader). The UI, downloader and paper texture blocks are left behind.
// No line inside a block is changed; the worker harness (src/workers/gen-worker.js) supplies
// the few browser globals the blocks touch.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const html = fs.readFileSync(path.join(ROOT, 'upstream', 'index.html'), 'utf8');
const blocks = [];
const re = /<script([^>]*)>([\s\S]*?)<\/script>/g;
let m;
while ((m = re.exec(html))) blocks.push({ attrs: m[1].trim(), body: m[2] });
const keep = blocks.slice(0, 6);
const ids = keep.map(b => (/id="([^"]+)"/.exec(b.attrs) || [, '(no id)'])[1]);
if (ids.join() !== 'PRNG,(no id),PerlinNoise,PolyTools,Util,(no id)') throw new Error('unexpected upstream layout: ' + ids.join());
const out = [
  '// GENERATED by tools/extract-engine.mjs from upstream/index.html. Do not edit by hand.',
  '// {Shan, Shui}* by Lingdong Huang, https://github.com/LingDong-/shan-shui-inf (MIT, see upstream/LICENSE).',
  '// Script blocks 1 to 6 of the original page, concatenated without changes.',
  '',
  ...keep.map((b, i) => `// ---- upstream <script${b.attrs ? ' ' + b.attrs : ''}> (block ${i + 1}) ----\n${b.body}\n`),
].join('\n');
fs.writeFileSync(path.join(ROOT, 'src', 'engine', 'upstream-engine.js'), out);
console.log('wrote src/engine/upstream-engine.js', out.length, 'bytes from blocks', ids.join(', '));
